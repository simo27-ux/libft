#include "libft.h"

int	ft_atoi(const char *str)
{
	int	i;
	int	resu;
	int	signe;

	resu = 0;
	signe = 1;
	i = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
		i++;
	if (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
			signe *= -1;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		resu = resu * 10 + str[i] - '0';
		i++;
	}
	return (resu * signe);
}
